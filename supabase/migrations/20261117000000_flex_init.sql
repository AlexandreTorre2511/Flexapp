-- Flex : schéma, sécurité et reprise des 291 cabinets.
-- Rejouable sans risque : rien n'est écrasé si les tables ou les cabinets existent déjà.

create extension if not exists pgcrypto;

create table if not exists public.cabinets (
  id text primary key default ('k' || substr(replace(gen_random_uuid()::text,'-',''),1,12)),
  nom text not null,
  ville text not null default '',
  secteur text not null default '06',
  mail text not null default '',
  statut text not null default 'a_contacter',
  gestionnaire text not null default '',
  tel text not null default '',
  rdv text not null default '',
  relance text not null default '',
  note text not null default '',
  journal jsonb not null default '[]'::jsonb,
  maj timestamptz not null default now()
);

create table if not exists public.demandes (
  id uuid primary key default gen_random_uuid(),
  date timestamptz not null default now(),
  marque text not null default '',
  cabinet text not null default '',
  adresse text not null default '',
  probleme text not null default '',
  urgence text not null default '',
  acces text not null default '',
  contact text not null default '',
  tel text not null default '',
  creneau text not null default '',
  statut text not null default 'nouvelle',
  montant numeric not null default 0,
  encaisse text not null default ''
);

-- Seuls les comptes créés dans Supabase (toi et la commerciale) lisent et écrivent.
alter table public.cabinets enable row level security;
alter table public.demandes enable row level security;

drop policy if exists "equipe_cabinets" on public.cabinets;
create policy "equipe_cabinets" on public.cabinets for all to authenticated using (true) with check (true);
drop policy if exists "equipe_demandes" on public.demandes;
create policy "equipe_demandes" on public.demandes for all to authenticated using (true) with check (true);

